<?php
// Build the tinydns data file from the DNS table (crm.dns) and compile it with tinydns-data.
// Run by cron every minute and by install.sh. Only rewrites data.cdb when the rows changed.
//   php /opt/dwalliance/current/cli/dw-dns-build.php [--force] [--print]
if (PHP_SAPI !== 'cli') { http_response_code(404); exit; }
require_once '/var/www/html/lib/Dw.php';

$root = getenv('DW_TINYDNS_ROOT') ?: '/var/lib/dwalliance/tinydns/root';
$force = in_array('--force', $argv, true);
$print = in_array('--print', $argv, true);

// tinydns-data field escaping: ':' , '\' and anything outside printable ASCII become \ooo octal.
function f(string $v): string
{
    $v = str_replace(["\r", "\n", "\0"], ' ', $v);
    $out = '';
    $n = strlen($v);
    for ($i = 0; $i < $n; $i++) {
        $c = $v[$i];
        $o = ord($c);
        $out .= ($c === ':' || $c === '\\' || $o < 32 || $o > 126) ? sprintf('\\%03o', $o) : $c;
    }
    return $out;
}
function host(string $v): string
{
    $v = strtolower(rtrim(trim($v), '.'));
    return preg_match('/^(\*\.)?[a-z0-9_.-]+$/', $v) ? $v : '';
}
function ip(string $v): string
{
    $v = trim($v);
    return filter_var($v, FILTER_VALIDATE_IP, FILTER_FLAG_IPV4) ? $v : '';
}

try {
    $dns = Dw::pdoDns();
} catch (Throwable $e) {
    fwrite(STDERR, date('c') . " dns build: " . $e->getMessage() . "\n");
    exit(1);
}
$rows = $dns->query('SELECT rr_id, rr_type, rr_fqdn, rr_ip, rr_target, rr_mx_dist, rr_ttl, rr_email, rr_serial, rr_refresh, rr_retry, rr_expire, rr_minimum FROM dns ORDER BY rr_id')->fetchAll(PDO::FETCH_ASSOC);
$lines = ["# Generated by dw-dns-build.php from crm.dns. Do not edit by hand."];
$skipped = 0;
foreach ($rows as $r) {
    $t = (string)$r['rr_type'];
    $fq = host((string)$r['rr_fqdn']);
    $ttl = (int)$r['rr_ttl'];
    $ip = ip((string)$r['rr_ip']);
    $target = (string)$r['rr_target'];
    if ($fq === '') { $skipped++; continue; }
    switch ($t) {
        case '+': case '=':
            if ($ip === '') { $skipped++; continue 2; }
            $lines[] = $t . f($fq) . ':' . $ip . ':' . $ttl;
            break;
        case 'C': case '^':
            $x = host($target);
            if ($x === '') { $skipped++; continue 2; }
            $lines[] = $t . f($fq) . ':' . f($x) . ':' . $ttl;
            break;
        case '@':
            $x = host($target);
            if ($x === '' && $ip === '') { $skipped++; continue 2; }
            $lines[] = '@' . f($fq) . ':' . $ip . ':' . f($x) . ':' . (int)$r['rr_mx_dist'] . ':' . $ttl;
            break;
        case '.': case '&':
            $x = host($target);
            if ($x === '' && $ip === '') { $skipped++; continue 2; }
            $lines[] = $t . f($fq) . ':' . $ip . ':' . f($x) . ':' . $ttl;
            break;
        case 'Z':
            $m = host($target);
            $email = str_replace('@', '.', strtolower(trim((string)$r['rr_email'])));
            $lines[] = 'Z' . f($fq) . ':' . f($m) . ':' . f($email) . ':' . ((int)$r['rr_serial'] ?: '') . ':' . ((int)$r['rr_refresh'] ?: '')
                . ':' . ((int)$r['rr_retry'] ?: '') . ':' . ((int)$r['rr_expire'] ?: '') . ':' . ((int)$r['rr_minimum'] ?: '') . ':' . $ttl;
            break;
        case "'":
            $lines[] = "'" . f($fq) . ':' . f($target) . ':' . $ttl;
            break;
        default:
            $skipped++;
    }
}
$data = implode("\n", $lines) . "\n";
if ($print) { echo $data; exit(0); }
if (!is_dir($root)) { fwrite(STDERR, "missing $root\n"); exit(1); }
$cur = @file_get_contents("$root/data");
if (!$force && $cur === $data && is_file("$root/data.cdb")) { exit(0); }
file_put_contents("$root/data.tmp", $data, LOCK_EX);
rename("$root/data.tmp", "$root/data");
$bin = trim((string)shell_exec('command -v tinydns-data')) ?: '/usr/bin/tinydns-data';
$cmd = 'cd ' . escapeshellarg($root) . ' && ' . escapeshellarg($bin) . ' 2>&1';
exec($cmd, $out, $rc);
if ($rc !== 0) { fwrite(STDERR, date('c') . " tinydns-data failed: " . implode(' ', $out) . "\n"); exit(1); }
echo date('c') . ' dns build: ' . count($rows) . ' rows, ' . $skipped . " skipped\n";
